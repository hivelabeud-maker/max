  /* ── 웨이브 카운터 ────────────────────────────────────────────────────
     레퍼런스가 "웨이브 14/20"이라 20칸으로 나눈다. 전투 구간(1.6~19.5초)을
     20등분한 값이고, 카운터는 0.9초마다 한 칸씩 오른다.
     ※ 스폰 난이도(waves[])는 여전히 3단계로 오른다. 20칸은 진행을 읽게 하는
        눈금이지 난이도 단계가 아니다 — 21.5초짜리에 난이도를 20단계로 쪼개면
        어느 단계도 인상에 남지 않는다.
     waveAt 은 1차의 하드코딩 삼항식(호출부 0건인 죽은 함수였다)을 waveSpan
     순회로 다시 썼다. 칸 수를 바꾸면 아래 배열만 고치면 된다.           */
  waveSpan : (function () {
    var a = [], N = 20, t0 = 1.6, t1 = 19.5, d = (t1 - t0) / N;
    for (var i = 0; i < N; i++) a.push([t0 + d * i, t0 + d * (i + 1)]);
    return a;
  })(),
  waveAt : function (t) {
    var sp = this.waveSpan;
    if (t <= sp[0][0]) return 1;
    for (var i = sp.length - 1; i >= 0; i--) if (t >= sp[i][0]) return i + 1;
    return 1;
  },

