#!/usr/bin/env bash
# UserPromptSubmit 훅 — 리서치/글 산출 자동 규칙 "조건부" 주입
# 매 프롬프트마다 실행되지만, 아래 키워드가 감지될 때만 규칙을 컨텍스트로 주입한다.
# (단순 질의·잡업에는 아무것도 붙이지 않아 조용함)

input=$(cat)
prompt=$(printf '%s' "$input" | jq -r '.prompt // ""')

ctx=""

# ── 리서치성 요청 감지 ──────────────────────────────
if printf '%s' "$prompt" | grep -qiE '리서치|와이드|동향|시장 ?조사|경쟁사|경쟁 ?구도|레퍼런스|벤치마크|트렌드|포지셔닝|화이트스페이스|조사해|분석해줘'; then
  ctx="[자동 규칙 · 리서치] 산출물로 바로 가지 말 것. market-research 에이전트 사양(.claude/agents/market-research.md · .claude/library/prompts/wide-research.md)을 그대로 따라 아래 출력을 먼저 낸다. '덱으로/제안서로' 지정이 있어도 이 리서치를 건너뛰지 않는다(리서치 → 그 결과로 덱).

원칙: (a)출처 필수 — 모든 브랜드 정보·주장에 출처(매체명+URL), 없으면 '추정' 명시. (b)객관 우선 — 유리한 결론 미리 정하지 않음. (c)축은 소비자 언어(감성↔기능, 대중↔프리미엄 등). (d)정밀도: 빠른 스캔 5~8개, '제대로/30개'면 폭넓게.

출력 형식 (Wide Research 6단계, 순서대로):
1. 조사 범위 — 카테고리 / '최근 6년 내 활동 중' / 브랜드 수(기본 30, 축소 시 명시) / 기준 시점. ※동종+이종업계 함께, 각 브랜드 [동종]/[이종] 태그.
2. 브랜드 분석 테이블 — 각 브랜드 8속성: 이름·로고(URL)·소재지·오픈시기·브랜드스토리·타겟층·기능/목적·출처(URL).
3. 3개 그룹 분류 — 인사이트 공통점으로 3그룹, 각 그룹 관점 한 줄(=발산 3방향 후보).
4. XY 포지셔닝 맵 — 소비자 대립축 X·Y 정의 → 브랜드/3그룹 사분면 배치, 군집·공백 짚기.
5. 화이트스페이스 — 빈 사분면 = 노릴 자리. 왜 비었는지(못 해서 vs 수요 없어서)까지 판단.
6. 시사점 — 관점·발산·견적에 주는 한 줄 함의.

깊이가 필요하면 market-research 에이전트를 Agent 툴로 스폰해 위 형식으로 산출한다. 산출 완료 후에는 반드시 다음 단계(관점 잡기/발산/트렌드·레퍼런스 보강/덱화 중 무엇으로 이어갈지)를 실장님께 되묻는다 — 마음대로 다음 단계로 넘어가지 않는다."
fi

# ── 글·덱·카피 산출 감지 ────────────────────────────
if printf '%s' "$prompt" | grep -qiE '덱|제안서|슬라이드|카피|캡션|뉴스레터|스레드|링크드인|원고|리포트|보고서|대본|글쓰|문구|본문 ?정리'; then
  [ -n "$ctx" ] && ctx="${ctx}"$'\n'
  ctx="${ctx}[자동 규칙 · 글 산출] 발행/제출 전 최종 필터로 dumbify(일반인 5초 이해: 전문용어 제거·한 문장 한 생각·구체 표현) + anti-ai-writing을 적용한다. 이미 대화체인 짧은 캡션엔 가볍게. 그리고 출처·레퍼런스는 텍스트가 아니라 항상 클릭 가능한 바로가기 링크(<a href> / 마크다운 링크)로 원문에 연결한다."
fi

if [ -n "$ctx" ]; then
  jq -cn --arg c "$ctx" '{hookSpecificOutput:{hookEventName:"UserPromptSubmit", additionalContext:$c}}'
fi
exit 0
